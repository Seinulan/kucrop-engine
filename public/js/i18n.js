let current = 'ru';
const idx = { ru: 0, kk: 1, en: 2 };

export function setLang(code) { current = idx[code] !== undefined ? code : 'ru'; return current; }
export function getLang() { return current; }
export function locale() { return (LANGS.find((l) => l.code === current) || LANGS[0]).locale; }

export function t(key, vars) {
  const row = D[key];
  let s = row ? (row[idx[current]] || row[0]) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
  return s;
}
